#!/usr/bin/env python3
"""
Figure out the correct mapping from garbled chars to real box chars.

The garbled chars in the file are: É, æ, û, ê, ò, ù, ö, ¥, Ü, Γ
These should be box/block drawing chars.

Strategy: looking at the LOGO pattern visually, deduce the mapping.
The LOGO displays as "PALADIN" in block art, using chars like:
  █ (full block)  
  ╔╗╚╝║═ (box drawing)

From looking at the garbled banner screenshot:
  Γûê = should be █ (full block U+2588) 
  Γòù = should be ╗ (U+2557) or similar
  Γòö = should be ╠ 
  Γòæ = should be ║ (vertical)
  Γò¥ = should be ╝
  ΓòÉ = should be ═ 
  Γòö = ...
  
Actually the simplest approach: look at the raw bytes in the file and 
decode them as cp437 to see if that recovers the block chars.

The file bytes for Γûê (U+0393 U+00FB U+00EA) are: CE 93 C3 BB C3 AA
These 6 bytes don't produce anything useful when re-decoded as cp437.

BUT: the original source of the file might have been a cp437 terminal where
█ = 0xDB. When saved/converted: 
  0xDB in cp437 = █  
  0xDB as a single byte in a UTF-8 file is invalid (it's > 0x7F)
  So the tool that created the file might have:
    - Read 0xDB as cp1252 char 'Û' (U+00DB)
    - Saved that as UTF-8: C3 9B
  
  C3 9B as UTF-8 = U+00DB = Û  
  But the file has CE 93 (Γ) C3 BB (û) C3 AA (ê)...
  
  CE 93 = U+0393 (Γ)
  This CANNOT come from a single latin-1 byte since U+0393 > U+00FF.
  
  UNLESS the file was saved by first writing byte 0x93 raw,
  then later "fixed" by a BOM-aware tool that re-read it as UTF-8:
  
  Byte sequence: 93 FB EA  
  Not valid UTF-8! The tool would replace 0x93 with U+FFFD (replacement char)?
  No — unless it decoded as cp1252 first:
    0x93 in cp1252 = U+201C = " (left double quotation mark)
    0xFB in cp1252 = U+00FB = û
    0xEA in cp1252 = U+00EA = ê
  Then THAT string was re-encoded as UTF-8: E2 80 9C C3 BB C3 AA
  But that gives 6 bytes, and U+201C ("), U+00FB (û), U+00EA (ê)...
  Still not what we see (U+0393).

The only codec I know where 0x93 maps to U+0393 is if someone used
the wrong codec. Let me systematically test all Python codecs.
"""
import sys, encodings.aliases
sys.stdout.reconfigure(encoding='utf-8')

target_char = chr(0x0393)  # Γ

print(f"Searching for codec where byte 0x93 -> U+0393 ({target_char}):")
all_encodings = set(encodings.aliases.aliases.values())
matches = []
for enc in sorted(all_encodings):
    try:
        ch = bytes([0x93]).decode(enc)
        if ch == target_char:
            matches.append(enc)
    except:
        pass

if matches:
    for m in matches:
        print(f"  Found: {m}")
else:
    print("  None found!")

print()

# Different approach: what if the file was generated by a Python script that
